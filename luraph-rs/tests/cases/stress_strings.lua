-- String stress: patterns, gsub (function + capture replacement),
-- format, byte/char, find anchors
local s = "Hello, World"
print("s1:", s:upper(), s:lower(), s:sub(1, 5), s:sub(-5))
print("s2:", string.rep("ab", 3), string.rep("", 5) == "")
print("s3:", string.format("%d %s %.2f", 42, "x", 3.14159))
print("s4:", string.format("%5d|%-5d|%07.3f", 42, 42, 3.5))
local g, n1 = ("hello world hello"):gsub("hello", "hi")
print("s5:", g, n1)
local g2, n2 = ("abc123def456"):gsub("(%d+)", "[%1]")
print("s6:", g2, n2)
local g3, n3 = ("a1b2c3"):gsub("(%d)", function(d)
	return (tonumber(d) * 2)
end)
print("s7:", g3, n3)
local g4, n4 = ("aaa"):gsub("a", "bb")
print("s8:", g4, n4)
print("f1:", ("  hi  "):find("hi"), ("abc"):find("b"), ("abc"):find("bc"), ("abc"):find("z"))
print("m1:", ("abc"):match("(.)(.)(.)"))
print("m2:", ("abc123"):match("(%a+)(%d+)"))
print("m3:", ("hello"):match("^h..l"), ("hello"):match("o$"), ("hello"):match("o$$"))
print("b1:", ("hello"):byte(1), ("hello"):byte(1, 3), ("A"):byte())
print("c1:", string.char(72, 101, 105), string.char(48, 49, 50))
print("g9:", ("tab\there"):gsub("\t", "_"))
print("m4:", ("aaa"):match("a*"), ("bbaa"):match("a+"))
print("m5:", ("a.b"):match("%."), ("abc"):match("a.c"), ("abc"):match("a.c"))
print("m6:", ("x1y22z333"):match("(%d+)%w"))
print("l1:", string.len("xy"), #("xy") .. "z")
local big = string.rep("0123456789", 500)
print("big:", #big, big:sub(2498, 2503))
local up = ("MixedCase"):gsub("(%u)", string.upper):gsub("(%l)", string.lower)
print("s9:", up)
