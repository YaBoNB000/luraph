-- luau_isyieldable.lua: coroutine.isyieldable + coroutine.close (Luau / 5.2+ only)
local y1 = coroutine.isyieldable()
local co = coroutine.create(function()
	local y2 = coroutine.isyieldable()
	coroutine.yield(y2)
end)
coroutine.resume(co)
print("isyieldable:", y1 == true)
-- close
local co2 = coroutine.create(function()
	coroutine.yield()
end)
coroutine.resume(co2)
coroutine.close(co2)
print("closed:", coroutine.status(co2))
print("luau isyieldable done")
